import React, { createContext, useContext, useEffect, useState } from 'react'

/* Bilingual UI (English / Amharic).
   Components call t('English text', 'የአማርኛ ጽሑፍ') and the active language
   decides which string renders. The choice persists in localStorage and
   applies to navigation, headers, tables, forms and actions app-wide. */

export type Lang = 'en' | 'am'

const LangCtx = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({ lang: 'en', setLang: () => {} })

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { return (localStorage.getItem('murago_lang') as Lang) || 'en' } catch { return 'en' }
  })
  const setLang = (l: Lang) => {
    setLangState(l)
    try { localStorage.setItem('murago_lang', l) } catch { /* ignore */ }
  }
  useEffect(() => { document.documentElement.lang = lang === 'am' ? 'am' : 'en' }, [lang])
  return <LangCtx.Provider value={{ lang, setLang }}>{children}</LangCtx.Provider>
}

export function useLang() { return useContext(LangCtx) }

/** Returns t(en, am) bound to the active language. */
export function useT() {
  const { lang } = useLang()
  return (en: string, am: string) => (lang === 'am' ? am : en)
}

/** Language switcher: EN | አማርኛ toggle used in the header and on login. */
export function LangSwitch({ dark = false }: { dark?: boolean }) {
  const { lang, setLang } = useLang()
  const btn = (l: Lang, label: string) => (
    <button key={l} onClick={() => setLang(l)} aria-pressed={lang === l}
      className="!px-2.5 !py-1 text-xs font-semibold rounded-md"
      style={lang === l
        ? { background: 'var(--btn-bg)', color: 'var(--btn-text)' }
        : { background: 'transparent', color: dark ? 'var(--sidebar-text)' : 'var(--muted)' }}>
      {label}
    </button>
  )
  return (
    <div className="inline-flex items-center gap-0.5 rounded-lg p-0.5" role="group" aria-label="Language / ቋንቋ"
      style={{ border: '1px solid var(--border)' }}>
      {btn('en', 'EN')}{btn('am', 'አማርኛ')}
    </div>
  )
}


